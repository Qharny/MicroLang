// MicroLang Example: Variables and Expressions
// Demonstrates all variable types and arithmetic

// Integer variables
x = 10
y = 3

// Arithmetic with precedence
sum = x + y
diff = x - y
product = x * y
quotient = x / y
complex = (x + y) * 2 - 1

print(sum)
print(diff)
print(product)
print(quotient)
print(complex)

// Float variables
pi = 3.14159
radius = 5
area = pi * radius * radius
print(area)

// String variables
greeting = "Hello"
name = "MicroLang"
print(greeting)
print(name)

// Boolean variables
isReady = true
isFinished = false
print(isReady)
print(isFinished)
